import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import prettier from 'prettier'

const methods = new Set([
  'get',
  'post',
  'put',
  'patch',
  'delete',
  'head',
  'options',
  'trace',
])

function enumKey(value) {
  const key = JSON.stringify(String(value))
  return value === '__proto__' ? `[${key}]` : key
}

function enumName(parts) {
  const name = parts
    .flatMap((part) => String(part).split(/[^a-zA-Z0-9$]+/))
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
  return /^[a-zA-Z_$]/.test(name) ? name : `Enum${name}`
}

function collectEnums(schema) {
  const enums = new Map()

  function visit(definition, parts) {
    if (!definition || typeof definition !== 'object') return
    const values =
      definition.enum ??
      (Object.hasOwn(definition, 'const') ? [definition.const] : undefined)
    if (Array.isArray(values)) {
      const name = enumName(parts)
      for (const value of values) {
        if (
          value !== null &&
          !['string', 'number', 'boolean'].includes(typeof value)
        )
          throw new Error(`Unsupported enum value in ${name}`)
      }
      if (new Set(values.map(String)).size !== values.length)
        throw new Error(`Enum member names collide in ${name}`)
      if (
        enums.has(name) &&
        JSON.stringify(enums.get(name)) !== JSON.stringify(values)
      )
        throw new Error(`Enum names collide: ${name}`)
      enums.set(name, values)
    }
    for (const [name, property] of Object.entries(definition.properties ?? {}))
      visit(property, [...parts, name])
    if (definition.items) visit(definition.items, [...parts, 'Item'])
    if (typeof definition.additionalProperties === 'object')
      visit(definition.additionalProperties, [...parts, 'Value'])
    for (const keyword of ['anyOf', 'oneOf', 'allOf']) {
      const variants = definition[keyword] ?? []
      const nonNull = variants.filter((variant) => variant.type !== 'null')
      for (const [index, variant] of nonNull.entries())
        visit(
          variant,
          nonNull.length === 1 ? parts : [...parts, keyword, String(index + 1)],
        )
    }
  }

  for (const [name, definition] of Object.entries(
    schema.components?.schemas ?? {},
  ))
    visit(definition, [name])
  for (const item of Object.values(schema.paths ?? {})) {
    for (const [method, operation] of Object.entries(item)) {
      if (!methods.has(method)) continue
      const id = operation.operationId
      for (const parameter of [
        ...(item.parameters ?? []),
        ...(operation.parameters ?? []),
      ])
        visit(parameter.schema, [id, parameter.in, parameter.name])
      for (const media of Object.values(operation.requestBody?.content ?? {}))
        visit(media.schema, [id, 'Request'])
      for (const [status, response] of Object.entries(
        operation.responses ?? {},
      ))
        for (const media of Object.values(response.content ?? {}))
          visit(media.schema, [id, 'Response', status])
    }
  }
  return [...enums].sort(([left], [right]) => left.localeCompare(right, 'en'))
}

export async function buildArtifacts(schema, root) {
  const endpoints = Object.create(null)
  const missingResponses = []
  for (const [route, item] of Object.entries(schema.paths).sort()) {
    for (const [method, operation] of Object.entries(item).sort()) {
      if (!methods.has(method)) continue
      const id = operation.operationId
      if (!id || id === '__proto__' || Object.hasOwn(endpoints, id)) {
        throw new Error(
          `Missing, reserved or duplicate operationId: ${method.toUpperCase()} ${route}`,
        )
      }
      const auth = operation['x-client-auth'] ?? 'required'
      if (!['required', 'none'].includes(auth))
        throw new Error(`Invalid x-client-auth for ${id}`)
      endpoints[id] = {
        operationId: id,
        method: method.toUpperCase(),
        path: route,
        auth,
      }
      for (const [status, response] of Object.entries(operation.responses)) {
        if (!status.startsWith('2')) continue
        const json = response.content?.['application/json']?.schema
        const csv = response.content?.['text/csv']?.schema
        const specified =
          (json && Object.keys(json).length > 0) || csv?.type === 'string'
        if (response.content && !specified) {
          missingResponses.push({
            operationId: id,
            method: method.toUpperCase(),
            path: route,
            status,
          })
        }
      }
    }
  }
  const banner = '// Generated by npm run api:generate. Do not edit manually.\n'
  const coverage = {
    operation_count: Object.keys(endpoints).length,
    unspecified_success_responses: missingResponses,
  }
  const declarations = await openapiTS(schema, {
    alphabetize: true,
    defaultNonNullable: false,
    emptyObjectsUnknown: true,
  })
  const componentDeclarations = declarations.filter(
    (declaration) => declaration.name?.text === 'components',
  )
  const contractDeclarations = declarations.filter(
    (declaration) => declaration.name?.text !== 'components',
  )
  const enums = collectEnums(schema)
  const enumDeclarations = enums.map(([name, values]) => {
    const members = values.map(
      (value) => `${enumKey(value)}: ${JSON.stringify(value)}`,
    )
    return (
      `export const ${name} = { ${members.join(',')} } as const\n` +
      `export type ${name} = (typeof ${name})[keyof typeof ${name}]\n`
    )
  })
  const outputs = {
    'client/api/api-types.ts': banner + astToString(componentDeclarations),
    'client/api/api-enums.ts':
      banner +
      enumDeclarations.join('\n') +
      `export const apiEnums = { ${enums.map(([name]) => name).join(',')} } as const\n`,
    'client/api/api-contract.ts':
      banner +
      "import type { components } from './api-types.ts'\n" +
      astToString(contractDeclarations),
    'client/api/api-endpoints.ts':
      banner +
      `export const apiEndpoints = ${JSON.stringify(endpoints, null, 2)} as const\n`,
    'client/api/api-coverage.json': JSON.stringify(coverage, null, 2),
  }
  for (const [relativePath, source] of Object.entries(outputs)) {
    const filename = path.join(root, relativePath)
    const options = await prettier.resolveConfig(filename)
    outputs[relativePath] = await prettier.format(source, {
      ...options,
      filepath: filename,
    })
  }
  return { outputs, coverage }
}

export async function writeArtifacts(root, outputs, check) {
  const stale = []
  for (const [relativePath, output] of Object.entries(outputs)) {
    const filename = path.join(root, relativePath)
    if (check) {
      let current
      try {
        current = await readFile(filename, 'utf8')
      } catch (error) {
        if (error.code !== 'ENOENT') throw error
      }
      if (current?.replace(/\r\n/g, '\n') !== output) stale.push(relativePath)
    } else {
      await mkdir(path.dirname(filename), { recursive: true })
      await writeFile(filename, output)
    }
  }
  return stale
}
